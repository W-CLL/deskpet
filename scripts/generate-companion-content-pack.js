function base(type, group, index, prompt, answer, tags) {
  return { id: `${type}:companion20260921:${group}:${String(index + 1).padStart(3, '0')}`,
    type, revision: 1, prompt, answer, explanation: '', choices: [], tags,
    difficulty: 1, locale: 'zh-CN', active: true };
}

function buildPack() {
  const items = songs.map(([prompt, answer, wrong, explanation, artist], index) => {
    const values = [answer, ...wrong.split('|')];
    const offset = index % 4;
    return { ...base('trivia', 'music', index, prompt, answer, ['音乐', '猜歌名', artist]),
      explanation, difficulty: 2, choices: [...values.slice(offset), ...values.slice(0, offset)] };
  });
  const labels = { mood: '心情', work: '工作', study: '学习' };
  for (const [group, rows] of Object.entries(care)) {
    assert.equal(rows.length, 30, `${group} care count`);
    rows.forEach(([prompt, answer], index) => items.push(base('care', group, index, prompt, answer, ['关怀', labels[group]])));
  }
  for (const [group, rows] of Object.entries(tips)) {
    assert.equal(rows.length, 20, `${group} tip count`);
    rows.forEach(([prompt, answer], index) => items.push(base('tip', group, index, prompt, answer, ['生活小贴士', labels[group]])));
  }
  assert.equal(songs.length, 60);
  assert.equal(items.length, 190);
  assert.ok(items.length <= MAX_IMPORT_ITEMS);
  assert.equal(new Set(items.map((item) => item.id)).size, items.length);
  assert.equal(new Set(items.map((item) => item.prompt)).size, items.length);
  for (const item of items) {
    normalizeContentItem(item, { requireId: true });
    if (item.type === 'trivia') {
      assert.equal(item.choices.length, 4);
      assert.ok(item.explanation.length > 0 && item.explanation.length <= 80);
    }
    assert.ok(item.answer.length <= 100);
  }
  return { items, disableMissing: false };
}

function main() {
  const pack = buildPack();
  const output = path.resolve(__dirname, '..', 'examples', 'advanced-content-packs', 'content-import.zh-CN-companion-190.json');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, `${JSON.stringify(pack, null, 2)}\n`, 'utf8');
  console.log(`Generated ${pack.items.length} items -> ${output}`);
}

