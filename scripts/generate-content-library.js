function rotate(values, offset) {
  const index = offset % values.length;
  return [...values.slice(index), ...values.slice(0, index)];
}

function quizChoices(records, index) {
  const values = [records[index][1]];
  for (let offset = 1; values.length < 4 && offset < records.length; offset += 1) {
    const candidate = records[(index + offset * 7) % records.length][1];
    if (!values.includes(candidate)) values.push(candidate);
  }
  return rotate(values, index);
}

function numericChoices(answer, step, unit, index) {
  const values = [answer, answer + step, Math.max(0, answer - step), answer + step * 2];
  let candidate = answer + step * 3;
  while (new Set(values).size < 4) {
    values.push(candidate);
    candidate += step;
  }
  const labels = [...new Set(values)].slice(0, 4).map((value) => `${value}${unit}`);
  return rotate(labels, index);
}

function makeMath() {
  const items = [];
  for (let index = 0; index < 20; index += 1) {
    const left = 14 + index * 3;
    const right = 7 + (index * 5) % 24;
    const answer = left + right;
    items.push({
      prompt: `${left} + ${right} 等于多少？`, answer: String(answer),
      explanation: `${left} + ${right} = ${answer}。`,
      choices: numericChoices(answer, 2 + index % 4, '', index), tags: ['加法', '心算'], difficulty: 1
    });
  }
  for (let index = 0; index < 20; index += 1) {
    const left = 3 + index % 8;
    const right = 5 + index;
    const answer = left * right;
    items.push({
      prompt: `${left} × ${right} 等于多少？`, answer: String(answer),
      explanation: `${left} × ${right} = ${answer}。`,
      choices: numericChoices(answer, left, '', index + 1), tags: ['乘法', '心算'], difficulty: index < 10 ? 1 : 2
    });
  }
  const rates = [10, 20, 25, 50];
  for (let index = 0; index < 20; index += 1) {
    const rate = rates[index % rates.length];
    const base = 40 + Math.floor(index / rates.length) * 40;
    const answer = base * rate / 100;
    items.push({
      prompt: `${base} 的 ${rate}% 是多少？`, answer: String(answer),
      explanation: `${base} × ${rate}% = ${answer}。`,
      choices: numericChoices(answer, Math.max(2, answer / 4), '', index + 2), tags: ['百分数', '应用题'], difficulty: 2
    });
  }
  for (let index = 0; index < 20; index += 1) {
    const answer = 3 + index;
    const multiplier = 2 + index % 4;
    const constant = 1 + index % 7;
    const result = answer * multiplier + constant;
    items.push({
      prompt: `如果 ${multiplier}x + ${constant} = ${result}，那么 x 等于多少？`, answer: String(answer),
      explanation: `两边先减 ${constant}，再除以 ${multiplier}，得到 x = ${answer}。`,
      choices: numericChoices(answer, 1 + index % 3, '', index + 3), tags: ['方程', '代数'], difficulty: 2
    });
  }
  for (let index = 0; index < 10; index += 1) {
    const length = 6 + index;
    const width = 3 + index % 5;
    const answer = 2 * (length + width);
    items.push({
      prompt: `长方形长 ${length} 厘米、宽 ${width} 厘米，周长是多少？`, answer: `${answer} 厘米`,
      explanation: `周长 = 2 ×（${length} + ${width}）= ${answer} 厘米。`,
      choices: numericChoices(answer, 2, ' 厘米', index + 4), tags: ['几何', '周长'], difficulty: 2
    });
  }
  for (let index = 0; index < 10; index += 1) {
    const base = 6 + index * 2;
    const height = 4 + index % 5;
    const answer = base * height / 2;
    items.push({
      prompt: `三角形底为 ${base} 厘米、高为 ${height} 厘米，面积是多少？`, answer: `${answer} 平方厘米`,
      explanation: `面积 = ${base} × ${height} ÷ 2 = ${answer} 平方厘米。`,
      choices: numericChoices(answer, Math.max(2, height), ' 平方厘米', index + 5), tags: ['几何', '面积'], difficulty: 2
    });
  }
  return items;
}

function commonItem(type, index, source) {
  return {
    id: `${type}:zhcn2026:${String(index + 1).padStart(3, '0')}`,
    type,
    revision: 1,
    prompt: source.prompt,
    answer: source.answer,
    explanation: source.explanation || '',
    choices: source.choices || [],
    tags: source.tags || [],
    difficulty: source.difficulty || 1,
    locale: 'zh-CN',
    active: true
  };
}

function buildLibraries() {
  const math = makeMath();
  return {
    joke: jokes.map(([prompt, answer, tag], index) => commonItem('joke', index, {
      prompt, answer, explanation: `这是围绕“${tag}”特点展开的拟人化冷笑话。`, tags: [tag, '冷笑话']
    })),
    math: math.map((source, index) => commonItem('math', index, source)),
    trivia: trivia.map(([prompt, answer, explanation, tag, difficulty], index) => commonItem('trivia', index, {
      prompt, answer, explanation, choices: quizChoices(trivia, index), tags: [tag, '趣味知识'], difficulty
    })),
    riddle: riddles.map(([prompt, answer, explanation], index) => commonItem('riddle', index, {
      prompt, answer, explanation, choices: quizChoices(riddles, index), tags: ['脑筋急转弯'], difficulty: index < 40 ? 1 : 2
    })),
    tip: tips.map(([prompt, answer, tag], index) => commonItem('tip', index, {
      prompt, answer, tags: [tag, '生活小贴士']
    })),
    care: care.map(([prompt, answer, tag], index) => commonItem('care', index, {
      prompt, answer, tags: [tag, '关怀']
    }))
  };
}

function validateLibrary(type, items) {
  if (items.length !== 100) throw new Error(`${type} 必须恰好包含 100 条，当前为 ${items.length} 条`);
  if (new Set(items.map((item) => item.id)).size !== items.length) throw new Error(`${type} 存在重复 ID`);
  for (const item of items) {
    if (item.type !== type || item.prompt.length < 2 || !item.answer) throw new Error(`${item.id} 基础字段无效`);
    if (item.choices.length && (item.choices.length < 2 || !item.choices.includes(item.answer))) {
      throw new Error(`${item.id} 的选项未包含答案`);
    }
    if (new Set(item.choices).size !== item.choices.length) throw new Error(`${item.id} 存在重复选项`);
  }
}

function main() {
  const libraries = buildLibraries();
  fs.mkdirSync(outputDirectory, { recursive: true });
  for (const [type, items] of Object.entries(libraries)) {
    validateLibrary(type, items);
    const outputPath = path.join(outputDirectory, `content-import.zh-CN-${type}-100.json`);
    fs.writeFileSync(outputPath, `${JSON.stringify({ items, disableMissing: false }, null, 2)}\n`, 'utf8');
    console.log(`${type}: ${items.length} -> ${outputPath}`);
  }
}

main();
